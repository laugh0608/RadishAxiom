#!/usr/bin/env python3
"""Check actual Rust v0.5 exports against frozen IR worlds and cached research bytes, offline.

The cache is generated by check-query-compaction.py from the exact legacy manifest;
its SMT, mapping, input and source digests are checked before reuse. No production
normalizer or prototype parser is used to interpret the actual new SMT.
"""
import argparse
import csv
import io
import json
from pathlib import Path
import re
import runpy
from types import SimpleNamespace

from p3_query_semantics import Interpreter
from p3_coverage_semantics import results as concrete_results
from p4b_replay_semantics import observe

ROOT = Path(__file__).resolve().parents[1]
HELPERS = runpy.run_path(str(ROOT / "scripts/check-query-compaction.py"))
for _name in ["digest", "json_bytes", "read_child", "independent_smt", "ax_worlds",
              "mapped_world", "visible", "verify_mapping", "mapping_rejections"]:
    globals()[_name] = HELPERS[_name]
LIMIT = 1_048_576
PROFILE = "axiom-p3-map-filter-query-v0.5"
BASE_FIELDS = ["input_slots", "value_cells", "expression_instances", "slot_comparisons", "smt_nodes", "output_bytes"]
COMPACT_FIELDS = ["normalized_nodes", "normalized_edges", "scratch_cells", "work_steps", "temporary_bytes", "integer_digits", "dag_depth"]


def key(row, production=False):
    return (row["candidate"], row["legacy_profile" if production else "profile"], row["target"])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("manifest", type=Path, help="actual --production Rust export")
    parser.add_argument("legacy_manifest", type=Path, help="unchanged original Rust export")
    parser.add_argument("prototype", type=Path, help="previous check-query-compaction.py output")
    parser.add_argument("output", type=Path, help="new result directory; never overwritten")
    args = parser.parse_args()
    raw_manifest = args.manifest.read_bytes()
    manifest = json.loads(raw_manifest)
    rows = manifest["rows"]
    limits = manifest["limits"]
    assert set(limits) == {"base", "compact", "legacy_base"}
    assert limits["base"]["max_output_bytes"] == LIMIT
    assert set(limits["compact"]) == {"max_" + f for f in COMPACT_FIELDS}
    raw_legacy = args.legacy_manifest.read_bytes()
    previous = json.loads(raw_legacy)["rows"]
    legacy = {key(row): row for row in previous}
    assert len(legacy) == len(previous)
    prototype_summary = json.loads((args.prototype / "summary.json").read_bytes())
    assert prototype_summary["manifest_raw"] == digest(raw_legacy)
    # Exporter is intentionally extended; all frozen Python semantic/prototype sources remain exact.
    for path, expected in prototype_summary["sources"].items():
        if path.endswith(".py"):
            assert digest((ROOT / path).read_bytes()) == expected, (path, "research source drift")
    corpus = bool(rows[0].get("corpus_path"))
    material_label = "corpus" if corpus else "ax"
    frozen_summary = json.loads((ROOT / f"docs/query/ax-b01-query-compaction-review/{material_label}-summary.json").read_bytes())
    assert all(prototype_summary[k] == value for k, value in frozen_summary.items())
    frozen_research = {(r["candidate"], r["profile"], r["target"]): r for r in csv.DictReader(
        io.StringIO((ROOT / f"docs/query/ax-b01-query-compaction-review/{material_label}-measurements.tsv").read_text()), delimiter="\t")}
    assert len(rows) == (790 if corpus else 27)
    assert len(previous) == (790 if corpus else 72)
    baseline = {}
    if not corpus:
        baseline = {(r["candidate"], r["profile"], r["target"]): r for r in csv.DictReader(
            io.StringIO((ROOT / "docs/query/ax-b01-query-size-review/measurements.tsv").read_text()), delimiter="\t")}
    checked_legacy = {}
    for old in previous:
        if baseline:
            frozen = baseline[key(old)]
            for field in ["query_raw", "query_bytes", "ir_raw", "p2_raw"]:
                assert str(old[field]) == frozen[field], (key(old), field)
        old_symbols_bytes = read_child(args.legacy_manifest.parent, old["symbols_path"])
        if old["query_raw"] in checked_legacy:
            assert checked_legacy[old["query_raw"]] == digest(old_symbols_bytes)
        if old["query_raw"] not in checked_legacy:
            data = read_child(args.legacy_manifest.parent, old["smt_path"])
            assert digest(data) == old["query_raw"] and len(data) == old["query_bytes"]
            old_symbols = json.loads(old_symbols_bytes)
            declarations = re.findall(rb"\(declare-const ([^ ()]+) (Bool|Int|Text)\)", data)
            assert {n.decode(): t.decode() for n, t in declarations} == {s["name"]: s["sort"] for s in old_symbols}
            checked_legacy[old["query_raw"]] = digest(old_symbols_bytes)
            del data
    args.output.mkdir(parents=True, exist_ok=False)
    cache, signatures, checked_cases, unique, measurements = {}, {}, set(), {}, []
    comparisons = layouts = replays = assertion_mutations = mapping_mutations = arithmetic_mutations = 0
    manual = {}
    for row in rows:
        assert row["profile"] == PROFILE
        assert row["query_rules"] == digest((ROOT / "docs/query/map-filter-query-v0.5.md").read_bytes())
        old = legacy[key(row, True)]
        frozen = frozen_research[key(row, True)]
        assert row["query_raw"] == frozen["compact_raw"]
        assert row["query_bytes"] == int(frozen["compact_bytes"])
        for field in ["ir_raw", "p2_raw", "definition", "kind"]:
            assert row[field] == old[field]
        assert row["legacy_query_raw"] == old["query_raw"]
        assert row["legacy_query_bytes"] == old["query_bytes"]
        old_symbols = json.loads(read_child(args.legacy_manifest.parent, old["symbols_path"]))
        assert row["legacy_symbols"] == old_symbols, "legacy symbols/origin drift"
        assert set(row["usage"]) == set(row["legacy_usage"]) == set(BASE_FIELDS)
        assert set(row["compact_usage"]) == set(COMPACT_FIELDS)
        assert all(0 <= v <= limits["base"]["max_" + f] for f, v in row["usage"].items())
        assert all(0 <= v <= limits["legacy_base"]["max_" + f] for f, v in row["legacy_usage"].items())
        assert all(0 <= v <= limits["compact"]["max_" + f] for f, v in row["compact_usage"].items())
        assert all(row["usage"][f] == row["legacy_usage"][f] for f in BASE_FIELDS[:-1])
        assert row["legacy_usage"]["output_bytes"] == old["query_bytes"]
        assert row["usage"]["output_bytes"] == row["query_bytes"]
        original = old["query_raw"]
        case, target_index = None, None
        if corpus:
            path = row["corpus_path"]
            if path not in cache:
                cache[path] = json.loads((ROOT / path).read_bytes())
            case = next(c for c in cache[path]["cases"] if c["name"] == row["case_name"])
            target_index = row["target_index"]
            assert case["targets"][target_index] == {"id": row["target"], "definition": row["definition"]}
            signature = digest(json_bytes([row["ir_raw"], case["worlds"], [e[target_index] for e in case["expected"]]]))
            assert original not in signatures or signatures[original] == signature
            signatures[original] = signature
        symbols_bytes = read_child(args.manifest.parent, row["symbols_path"])
        if original in unique:
            assert unique[original]["query_raw"] == row["query_raw"]
            assert unique[original]["query_bytes"] == row["query_bytes"]
            assert unique[original]["symbols_raw"] == digest(symbols_bytes)
        if original not in unique:
            data = read_child(args.manifest.parent, row["smt_path"])
            assert digest(data) == row["query_raw"] and len(data) == row["query_bytes"] <= LIMIT
            stem = original.removeprefix("sha256:")
            prototype_bytes = read_child(args.prototype, stem + ".smt2")
            research = prototype_summary["unique"][original]
            assert digest(prototype_bytes) == research["compact_raw"]
            assert len(prototype_bytes) == research["compact_bytes"]
            assert data == prototype_bytes, (row["candidate"], row["kind"], "actual Rust/prototype bytes differ")
            mapping = json.loads(read_child(args.prototype, stem + ".mapping.json"))
            actual_symbols = json.loads(read_child(args.manifest.parent, row["symbols_path"]))
            assert actual_symbols == [{"name": m["new"], "sort": m["sort"], "origin": m["origin"]} for m in mapping]
            compact, alpha = independent_smt(data)
            old_model = SimpleNamespace(symbols={s["name"]: s["sort"] for s in old_symbols})
            verify_mapping(old_model, compact, alpha, old_symbols, mapping)
            if not mapping_mutations and len(mapping) >= 2:
                mapping_mutations = mapping_rejections(old_model, compact, alpha, old_symbols, mapping)
            document_bytes = (ROOT / row["ir_path"]).read_bytes()
            assert digest(document_bytes) == row["ir_raw"]
            document = json.loads(document_bytes)
            if case is not None:
                case_key = (row["corpus_path"], case["name"])
                if case_key not in checked_cases:
                    for world, expected in zip(case["worlds"], case["expected"], strict=True):
                        assert concrete_results(document, world, case["targets"]) == expected
                    checked_cases.add(case_key)
                worlds = [(str(i), world) for i, world in enumerate(case["worlds"])]
                expectations = [e[target_index] for e in case["expected"]]
            else:
                worlds = ax_worlds(document)
                expectations = [concrete_results(document, w, [{"definition": row["definition"]}])[0] for _, w in worlds]
            got_true = got_false = False
            for (label, world), expected in zip(worlds, expectations, strict=True):
                assignment = Interpreter(document, world).assignment(old_symbols)
                mapped = {alpha[m["new"]]: assignment[m["old"]] for m in mapping}
                actual = compact.evaluate(mapped)
                assert actual == expected, (row["candidate"], row["kind"], label, "actual Rust SMT")
                comparisons += 1
                restored = mapped_world(document, old_symbols, mapping, assignment)
                assert visible(restored) == visible(world)
                layouts += 1
                got_true |= actual
                got_false |= not actual
                if not corpus:
                    observation = observe(document, restored, row["definition"])
                    assert (observation["kind"] == "target-violated") == actual
                    replays += 1
                    if row["kind"] == "contract-guarantee" and label in {"zero-net", "nonzero-net"}:
                        manual[(row["candidate"], label)] = actual
            for literal, detected in [(b"false", got_true), (b"true", got_false)]:
                if detected:
                    changed = re.sub(rb"(?m)^\(assert .*\)$", b"(assert " + literal + b")", data)
                    bad, bad_alpha = independent_smt(changed)
                    world, expected = next((w, e) for (_, w), e in zip(worlds, expectations, strict=True) if e != (literal == b"true"))
                    assignment = Interpreter(document, world).assignment(old_symbols)
                    assert bad.evaluate({bad_alpha[m["new"]]: assignment[m["old"]] for m in mapping}) != expected
                    assertion_mutations += 1
            if row["candidate"] == "int-add" and row["kind"] == "numeric-range":
                changed = data.replace(b"(+ ", b"(- ", 1)
                assert changed != data
                bad, bad_alpha = independent_smt(changed)
                found = False
                for (_, world), expected in zip(worlds, expectations, strict=True):
                    assignment = Interpreter(document, world).assignment(old_symbols)
                    found |= bad.evaluate({bad_alpha[m["new"]]: assignment[m["old"]] for m in mapping}) != expected
                assert found, "arithmetic mutation escaped independent check"
                arithmetic_mutations += 1
            unique[original] = {"query_raw": row["query_raw"], "query_bytes": len(data), "finite_assignments": len(worlds), "symbols_raw": digest(symbols_bytes)}
            print(f"{len(unique)} actual Rust SMT / {row['candidate']} / {row['kind']}: {len(data)} bytes", flush=True)
        measurements.append({f: row[f] for f in ["candidate", "ir_path", "ir_raw", "p2_raw", "profile", "legacy_profile", "kind", "target", "query_rules", "query_raw", "query_bytes", "legacy_query_raw", "legacy_query_bytes"]}
                            | {"free_symbols": len(old_symbols), "symbols_raw": digest(symbols_bytes), "within_1mib": True}
                            | {f"base_{k}": v for k, v in row["usage"].items()}
                            | {f"legacy_{k}": v for k, v in row["legacy_usage"].items()}
                            | row["compact_usage"])
    if manual:
        assert manual == {(f"ax-b01-{c}", label): (c == "wrong-add" or (c == "wrong-drop-zero" and label == "zero-net"))
                          for c in ["correct", "wrong-add", "wrong-drop-zero"] for label in ["zero-net", "nonzero-net"]}
    assert comparisons == (12553 if corpus else 324)
    assert assertion_mutations == (439 if corpus else 31)
    assert arithmetic_mutations == (1 if corpus else 0)
    assert mapping_mutations == 5
    assert len(unique) == (336 if corpus else 27)
    with (args.output / "measurements.tsv").open("w", newline="") as output:
        writer = csv.DictWriter(output, fieldnames=list(measurements[0]), delimiter="\t", lineterminator="\n")
        writer.writeheader()
        writer.writerows(measurements)
    sources = ["scripts/check-compact-query-production.py", "scripts/check-query-compaction.py",
               "scripts/query_compaction_prototype.py", "scripts/check-p3-query-semantics.py",
               "scripts/p3_query_semantics.py", "scripts/p3_totality_semantics.py", "scripts/p3_cardinality_semantics.py",
               "scripts/p3_coverage_semantics.py", "scripts/p4b_replay_semantics.py",
               "crates/axiom-ir/examples/export_query_compaction_inputs.rs", "crates/axiom-ir/src/query.rs",
               "docs/query/map-filter-query-v0.5.md", "docs/query/p4-request-response-model-v0.2.md"]
    sources += [str(p.relative_to(ROOT)) for p in sorted((ROOT / "crates/axiom-ir/src/query").rglob("*.rs"))]
    sources += [f"docs/query/ax-b01-query-compaction-review/{material_label}-summary.json",
                f"docs/query/ax-b01-query-compaction-review/{material_label}-measurements.tsv"]
    sources += sorted({row["ir_path"] for row in rows}) + sorted(cache)
    if not corpus:
        sources += ["docs/query/ax-b01-query-size-review/measurements.tsv"]
    summary = {"status": "actual-rust-compact-query-finite-validation-not-proof-not-solver",
               "accepted_baseline": "14a9693297333cf1bfec115d73e9ab4ec9247c8a", "manifest_raw": digest(raw_manifest), "legacy_manifest_raw": digest(raw_legacy),
               "prototype_summary_raw": digest((args.prototype / "summary.json").read_bytes()),
               "sources": {p: digest((ROOT / p).read_bytes()) for p in sources},
               "production_records": len(rows), "legacy_records_checked": len(previous),
               "legacy_unique_bytes_and_full_symbols_checked": len(checked_legacy),
               "unique_original_queries": len(unique),
               "unique_compact_queries": len({row["query_raw"] for row in rows}), "actual_rust_smt_compared_to_prototype": len(unique),
               "finite_comparisons": comparisons, "mapping_world_checks": layouts, "independent_replay_checks": replays,
               "assertion_mutations_detected": assertion_mutations, "arithmetic_mutations_detected": arithmetic_mutations,
               "mapping_mutation_classes_rejected": mapping_mutations, "stdin_limit_bytes": LIMIT,
               "query_min_bytes": min(m["query_bytes"] for m in measurements),
               "query_max_bytes": max(m["query_bytes"] for m in measurements),
               "minimum_headroom_bytes": LIMIT - max(m["query_bytes"] for m in measurements),
               "compact_usage_maxima": {f: max(m[f] for m in measurements) for f in COMPACT_FIELDS},
               "diagnostic_base_limits": limits["base"],
               "diagnostic_compact_limits": limits["compact"],
               "legacy_diagnostic_base_limits": limits["legacy_base"]}
    (args.output / "summary.json").write_bytes(json_bytes(summary))
    print(json.dumps({k: v for k, v in summary.items() if k != "sources"}, ensure_ascii=False), flush=True)


if __name__ == "__main__":
    main()
